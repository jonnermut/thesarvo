/** Attributes we don't model explicitly, kept so nothing is lost on a round trip. */
export type Other = Record<string, string>

/** A generic XML element, used for anything the model doesn't know about. */
export type RawElement = {
  tag: string
  attrs: Record<string, string>
  children: RawElement[]
  text: string
}

export type Guide = {
  /** Page id from the index, e.g. "167". */
  id: string
  guideStars: string
  nodes: GuideNode[]
  other: Other
}

export type GuideNode = Header | Climb | TextBlock | ImageTopo | Gps | UnknownNode

/** Text fields may contain `<br/>` for line breaks; see `splitLines`. */
export type Header = {
  type: 'header'
  id: string
  name: string
  rock: string
  sun: string
  walk: string
  access: string
  camping: string
  acknowledgement: string
  intro: string
  history: string
  autonumber: string
  other: Other
}

/** A boulder problem is a climb with `type: 'problem'`. */
export type Climb = {
  type: 'climb' | 'problem'
  id: string
  name: string
  number: string
  grade: string
  extra: string
  length: string
  /** "", "*", "**" or "***". */
  stars: string
  fa: string
  text: string
  other: Other
}

export type TextBlock = {
  type: 'text'
  id: string
  /** e.g. "text", "heading2", "heading3". */
  cls: string
  text: string
  other: Other
}

export type Point = { x: number; y: number; kind: string }

export type LineStyle = 'solid' | 'dashed' | 'dotted'

export type RoutePath = {
  id: string
  points: Point[]
  /** SVG path data. Generated by the editor, so we can draw without re-deriving curves. */
  d: string
  /** Id of the climb this line is for. */
  linkedTo: string
  lineStyle: LineStyle
  labelText: string
  arrow: boolean
  other: Other
}

export type RectStyle =
  | 'black_text_on_solid_white'
  | 'white_text_on_solid_black'
  | 'black_text_on_solid_yellow'
  | 'white_outline'
  | 'yellow_outline'

export type TopoRect = {
  id: string
  x: number
  y: number
  width: number
  height: number
  style: RectStyle
  arrowDirection: string
  text: string
  other: Other
}

export type ImageTopo = {
  type: 'image'
  id: string
  src: string
  width: number
  height: number
  noPrint: boolean
  printLayout: string
  legendTitle: string
  legendFooter: string
  legendX: number
  legendY: number
  /** Climb ids listed in the legend, in order. */
  legend: string[]
  paths: RoutePath[]
  rects: TopoRect[]
  /** Drawing elements we don't render yet (polyline, polygon...). */
  otherShapes: RawElement[]
  other: Other
}

export type GpsPoint = {
  pid: string
  code: string
  description: string
  zone: string
  easting: string
  northing: string
  latitude: string
  longitude: string
  height: string
  other: Other
}

export type Gps = { type: 'gps'; id: string; points: GpsPoint[]; other: Other }

export type UnknownNode = { type: 'unknown'; raw: RawElement }
